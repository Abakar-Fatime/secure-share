export type Lang = "en" | "fr";
export type TKey = Key;

interface I18n {
  lang: Lang;
  t: (key: Key) => string;
  toggle: () => void;
  action: (a: string) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("ss_lang");
    if (saved === "en" || saved === "fr") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.startsWith("fr") ? "fr" : "en";
}

export function I18nProvider({ children, lang: forced }: { children: ReactNode; lang?: Lang }) {
  const [lang, setLang] = useState<Lang>(forced ?? initialLang);
  const toggle = useCallback(() => {
    setLang((l) => {
      const next = l === "en" ? "fr" : "en";
      try {
        localStorage.setItem("ss_lang", next);
      } catch {
        /* storage unavailable */
      }
      document.documentElement.lang = next;
      return next;
    });
  }, []);
  const value = useMemo<I18n>(
    () => ({
      lang,
      toggle,
      t: (key) => (lang === "fr" ? fr : en)[key],
      action: (a) => ACTION_LABELS[a]?.[lang] ?? a,
    }),
    [lang, toggle],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside provider");
  return v;
}
